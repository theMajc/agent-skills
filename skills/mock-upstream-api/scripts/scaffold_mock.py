def main():
    parser = argparse.ArgumentParser(description="Scaffold Mock Upstream API Server")
    parser.add_argument("--entity", default="item", help="Entity singular name (e.g. user, transaction, order)")
    parser.add_argument("--fields", default="", help="Comma-separated field:type pairs (e.g. id:uuid,name:string,email:string,status:string,amount:number,createdAt:datetime)")
    parser.add_argument("--schema", default="", help="Path to JSON file or schema to infer entity fields and items")
    parser.add_argument("--count", type=int, default=50, help="Number of mock items to seed (default: 50)")
    parser.add_argument("--port", type=int, default=4000, help="Server port (default: 4000)")
    parser.add_argument("--flavor", choices=["node-builtin", "express-js", "fastapi", "json-server"], default="node-builtin", help="Server framework flavor (default: node-builtin)")
    parser.add_argument("--rate-limit", type=int, default=10, help="Max requests allowed per window (default: 10)")
    parser.add_argument("--rate-window", type=int, default=10, help="Rate limit sliding window in seconds (default: 10)")
    parser.add_argument("--output", default="", help="Output file path (default: stdout or ./mock-server.<ext>)")

    args = parser.parse_args()

    # Load from schema file if provided
    items = []
    entity = args.entity.lower()
    if args.schema and os.path.exists(args.schema):
        with open(args.schema, 'r', encoding='utf-8') as f:
            raw_data = json.load(f)
            if isinstance(raw_data, list):
                items = raw_data
            elif isinstance(raw_data, dict):
                if "data" in raw_data and isinstance(raw_data["data"], list):
                    items = raw_data["data"]
                elif "items" in raw_data and isinstance(raw_data["items"], list):
                    items = raw_data["items"]
                else:
                    items = [raw_data]

    if not items:
        fields = parse_fields(args.fields)
        items = generate_seed_data(entity, fields, args.count)

    # Render target flavor
    content = ""
    default_filename = ""
    if args.flavor == "node-builtin":
        content = render_node_builtin(entity, items, args.port, args.rate_limit, args.rate_window)
        default_filename = "mock-server.mjs"
    elif args.flavor == "express-js":
        content = render_express_js(entity, items, args.port, args.rate_limit, args.rate_window)
        default_filename = "mock-server.js"
    elif args.flavor == "fastapi":
        content = render_fastapi(entity, items, args.port, args.rate_limit, args.rate_window)
        default_filename = "mock-server.py"
    elif args.flavor == "json-server":
        db_payload = {f"{entity}s": items}
        mw_content = render_json_server_middleware(args.rate_limit, args.rate_window)
        if args.output:
            out_dir = args.output if os.path.isdir(args.output) else os.path.dirname(args.output) or "."
            os.makedirs(out_dir, exist_ok=True)
            with open(os.path.join(out_dir, "db.json"), "w", encoding="utf-8") as f:
                json.dump(db_payload, f, indent=2)
            with open(os.path.join(out_dir, "middleware.js"), "w", encoding="utf-8") as f:
                f.write(mw_content)
            print(f"Wrote {os.path.join(out_dir, 'db.json')} and {os.path.join(out_dir, 'middleware.js')}")
            return
        else:
            print(json.dumps(db_payload, indent=2))
            return

    if args.output:
        out_path = args.output
        if os.path.isdir(out_path):
            out_path = os.path.join(out_path, default_filename)
        os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(content)
