def generate_sample_value(field_name: str, field_type: str, index: int):
    field_lower = field_name.lower()
    type_lower = field_type.lower()
    
    if "id" in field_lower and type_lower in ("uuid", "string"):
        return f"mock-{field_name}-{index + 1:04d}"
    if type_lower == "uuid":
        return str(uuid.uuid4())
    if type_lower in ("int", "integer", "number"):
        if "amount" in field_lower or "price" in field_lower:
            return round(10.0 + (index * 7.5) % 500, 2)
        if "count" in field_lower or "quantity" in field_lower:
            return (index * 3) % 50 + 1
        return index + 1
    if type_lower in ("float", "double"):
        return round(1.5 + (index * 0.75), 2)
    if type_lower in ("bool", "boolean"):
        return index % 2 == 0
    if type_lower in ("datetime", "timestamp", "date"):
        return datetime.fromtimestamp(1700000000 + (index * 86400), tz=timezone.utc).isoformat()
    if type_lower == "email" or "email" in field_lower:
        return f"user{index + 1}@example.com"
    if "name" in field_lower:
        first_names = ["Alex", "Jordan", "Taylor", "Morgan", "Sam", "Casey", "Riley", "Chris", "Jamie", "Pat"]
        return f"{first_names[index % len(first_names)]} {index + 1}"
    if "status" in field_lower:
        statuses = ["active", "pending", "completed", "archived", "failed"]
        return statuses[index % len(statuses)]
    if "role" in field_lower:
        roles = ["admin", "member", "viewer", "editor"]
        return roles[index % len(roles)]
    if "url" in field_lower:
        return f"https://api.example.com/{field_name}/{index + 1}"
    
    return f"sample_{field_name}_{index + 1}"

def parse_fields(fields_str: str):
    fields = {}
    if not fields_str:
        return {"id": "string", "name": "string", "status": "string", "createdAt": "datetime"}
    for item in fields_str.split(","):
        item = item.strip()
        if not item:
            continue
        if ":" in item:
            k, v = item.split(":", 1)
            fields[k.strip()] = v.strip()
        else:
            fields[item] = "string"
    return fields

def generate_seed_data(entity: str, fields: dict, count: int):
    items = []
    for i in range(count):
        row = {}
        for k, v in fields.items():
            row[k] = generate_sample_value(k, v, i)
        items.append(row)
    return items

